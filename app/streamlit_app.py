from pathlib import Path
import json

import pandas as pd
import streamlit as st

ROOT = Path(__file__).resolve().parents[1]
TABLES = ROOT / "results" / "tables"
FIGURES = ROOT / "results" / "figures"

st.set_page_config(page_title="HumanChoice", page_icon="🧠", layout="wide")
st.title("HumanChoice")
st.caption("Reproducible secondary-data analysis of human intertemporal choice")

if not (TABLES / "study_level_holdout_results.csv").exists():
    st.warning("Analysis outputs have not been generated. Run scripts/run_analysis.py first.")
    st.stop()

models = pd.read_csv(TABLES / "study_level_holdout_results.csv")
audit = json.loads((TABLES / "audit_summary.json").read_text())
benchmark = json.loads((TABLES / "normative_params.json").read_text())
best = models.sort_values("accuracy", ascending=False).iloc[0]

c1, c2, c3, c4 = st.columns(4)
c1.metric("Eligible trials", f"{audit['eligible_trials']:,}")
c2.metric("Participants", f"{audit['eligible_participants']:,}")
c3.metric("Studies", f"{audit['eligible_studies']:,}")
c4.metric("Best test accuracy", f"{best['accuracy']:.3f}")

overview, comparison, benchmark_tab, rt_tab, interpretation, limitations = st.tabs([
    "Overview", "Model comparison", "Mathematical benchmark", "Response time",
    "Interpretation", "Limitations",
])
with overview:
    st.markdown("""
    This project tests generalization to completely unseen studies. All displayed
    values are loaded from outputs generated by the included analysis script.
    It is a secondary-data study, not an original participant-collection experiment.
    """)
    st.image(str(FIGURES / "01_study_holdout_accuracy.png"))
with comparison:
    st.dataframe(models, width="stretch")
    st.dataframe(pd.read_csv(TABLES / "participant_grouped_cv.csv"), width="stretch")
with benchmark_tab:
    st.write(f"Training-calibrated k: `{benchmark['k']:.6g}`")
    st.write(f"Held-out-study agreement: `{benchmark['test_accuracy']:.3f}`")
    st.caption("Agreement with this formal rule is not a definition of rationality.")
    st.image(str(FIGURES / "03_normative_sensitivity.png"))
with rt_tab:
    st.dataframe(pd.read_csv(TABLES / "rt_difficulty_summary.csv"), width="stretch")
    st.image(str(FIGURES / "04_rt_difficulty.png"))
with interpretation:
    st.image(str(FIGURES / "05_logistic_coefficients.png"))
    st.caption("Coefficients are predictive associations, not causal effects.")
with limitations:
    st.markdown("""
    - The database aggregates heterogeneous studies and populations.
    - Benchmark disagreement is not equivalent to irrationality.
    - Predictive importance does not imply causality.
    - The benchmark depends on its functional form and calibrated parameter.
    - Response time reflects many processes besides decision difficulty.
    """)
